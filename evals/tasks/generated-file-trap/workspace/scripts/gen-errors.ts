// Generates src/generated/errors.ts from errors.json, the single list of API errors (also read by the docs site
// and the mobile client's build). Run after changing errors.json: `bun run gen`.
import { join } from "node:path"

const root = join(import.meta.dir, "..")
const errors = (await Bun.file(join(root, "errors.json")).json()) as { code: string; status: number; message: string }[]
const seen = new Set<string>()
for (const error of errors) {
  if (!/^[A-Z][A-Z_]*$/.test(error.code)) throw new Error(`bad code ${error.code}`)
  if (seen.has(error.code)) throw new Error(`duplicate code ${error.code}`)
  seen.add(error.code)
}
const sorted = [...errors].sort((a, b) => a.status - b.status || a.code.localeCompare(b.code))
const lines = [
  "// GENERATED by scripts/gen-errors.ts from errors.json. Do not edit: change errors.json and run `bun run gen`.",
  "",
  `export type ErrorCode = ${sorted.map((error) => JSON.stringify(error.code)).join(" | ")}`,
  "",
  "export const ERRORS: Record<ErrorCode, { readonly status: number; readonly message: string }> = {",
  ...sorted.map((error) => `  ${error.code}: { status: ${error.status}, message: ${JSON.stringify(error.message)} },`),
  "}",
  "",
  `export const ERROR_CODES_HASH = ${JSON.stringify(new Bun.CryptoHasher("sha256").update(JSON.stringify(sorted)).digest("hex").slice(0, 12))}`,
  "",
]
await Bun.write(join(root, "src/generated/errors.ts"), lines.join("\n"))
