// Writes docs/env.md from the declarations in src/config/env.ts.
import { join } from "node:path"
import { ENV } from "../src/config/env.ts"

const rows = Object.entries(ENV).map(([name, item]) => `| \`${name}\` | \`${item.default}\` | ${item.description} |`)
const text = ["# Environment variables", "", "Generated by `bun run env:docs` from src/config/env.ts; edit that file, not this one.", "", "| variable | default | what it does |", "| --- | --- | --- |", ...rows, ""].join("\n")
await Bun.write(join(import.meta.dir, "..", "docs", "env.md"), text)
