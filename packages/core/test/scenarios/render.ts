/**
 * Renders the scenarios as the "Scenarios" section of
 * docs/step-loop-scenarios.md. The section between the two markers in that
 * file is this module's output: `bun scripts/scenario-doc.ts` rewrites it, and
 * `scenarios.test.ts` fails when the two differ.
 */
import type { Projection } from "../../src/message/message.ts"
import { allFamilies as families } from "./index.ts"
import { type MessageView, type Scenario, describeEvent, fold, historyIds, opening, openingIn, view } from "./script.ts"

export const SCENARIOS_START = "<!-- scenarios:start (generated by scripts/scenario-doc.ts; do not edit by hand) -->"
export const SCENARIOS_END = "<!-- scenarios:end -->"

/** The two ways a scenario begins: without snapshots, and with the workspace recorded before the prompt is delivered. */
const OPENINGS = [openingIn(), opening()].map((events) => events.map(describeEvent))

/** The whole generated section, without the markers. */
export function renderScenarios(): string {
  let number = 0
  return Object.entries(families)
    .map(([family, scenarios]) =>
      [`### ${family}`, ...scenarios.map((scenario) => renderScenario(scenario, ++number))].join("\n\n"),
    )
    .join("\n\n")
}

function renderScenario(scenario: Scenario, number: number): string {
  let state: Projection | null = null
  const lines: string[] = []
  const rejected: string[] = []
  for (const phase of scenario.phases) {
    lines.push(`-- ${phase.label}`)
    const described = phase.events.map(describeEvent)
    const first = (state?.lastSeq ?? 0) + 1
    // Most scenarios start with the same few events; they are shown as one line.
    const unquoted = (line: string | undefined) => line?.replace(/"[^"]*"$/, "")
    const opened = first === 1 ? OPENINGS.find((lines) => lines.every((line, index) => unquoted(described[index]) === unquoted(line))) : undefined
    const skipped = opened?.length ?? 0
    if (opened !== undefined) lines.push(`1-${skipped}  opening: ${opened.map((line) => line.replace(/ steer "[^"]*"$/, "")).join(", ")}`)
    described.slice(skipped).forEach((line, index) => {
      lines.push(`${String(first + index + skipped).padStart(3)}  ${line}`)
    })
    state = fold(state, phase.events)
    for (const rejection of phase.rejects ?? [])
      rejected.push(`- after "${phase.label}": \`${describeEvent(rejection.event)}\` (${rejection.code}). ${sentence(rejection.why)}`)
  }
  const end = state!
  return [
    `#### ${number}. ${scenario.title}`,
    scenario.description,
    `*Provider:* ${scenario.provider}.`,
    ...(scenario.setup === undefined ? [] : [describeSetup(scenario.setup)]),
    ...(scenario.contextWindow === undefined ? [] : [`*Context window:* ${scenario.contextWindow.toLocaleString("en-US")} tokens.`]),
    ...(scenario.approval === undefined ? [] : [describeApproval(scenario.approval)]),
    ...(scenario.features === undefined ? [] : [describeFeatures(scenario.features)]),
    ["```", ...lines, "```"].join("\n"),
    `*UI:* ${view(end).map(describeMessage).join(" · ")}. *Claim:* ${describeClaim(end)}.${end.inbox.length > 0 ? ` *Inbox:* ${end.inbox.map((item) => `${item.messageId} (${item.delivery})`).join(", ")}.` : ""}`,
    `*Model sees next:* ${historyIds(end).join(", ") || "nothing"}.`,
    ...(rejected.length > 0 ? [["*The reducer rejects:*", ...rejected].join("\n")] : []),
  ].join("\n\n")
}

function describeSetup(setup: NonNullable<Scenario["setup"]>): string {
  const config = setup.config === undefined ? "no configuration file" : `configuration \`${JSON.stringify(setup.config)}\``
  return `*Setup:* snapshots on; the workspace holds ${Object.keys(setup.files).join(", ")}; ${config}.`
}

function describeApproval(approval: NonNullable<Scenario["approval"]>): string {
  const sandbox = approval.sandbox === "unavailable" ? "no sandbox on the machine" : "the sandbox is available"
  const who = approval.attended === true ? "a person is present" : `nobody is present (unattended: ${approval.unattended ?? "deny"})`
  return `*Approval:* mode ${approval.mode ?? "auto"}; ${sandbox}; ${who}.`
}

function describeFeatures(features: NonNullable<Scenario["features"]>): string {
  const offered = [
    ...(features.skills === true ? ["skills (the `skill` tool; the project has skill files)"] : []),
    ...(features.mcp === true ? ["MCP (`mcp_search` and `mcp_call`; the user's configuration names one server, `fx`)"] : []),
    ...(features.wake === true ? ["wake-ups (`wake_create`, `wake_list`, `wake_cancel`)"] : []),
    ...(features.todo === true ? ["the real `todo` tool"] : []),
    ...(features.agents === true ? ["agents (the project has agent definitions)"] : []),
    ...(features.commands === true ? ["slash commands (the project has command files)"] : []),
    ...(features.telemetry === true ? ["live telemetry (the user's configuration turns it on and names a collector)"] : []),
    ...(features.hooks === undefined ? [] : [`hooks (the user's configuration: \`${JSON.stringify(features.hooks)}\`)`]),
    ...(features.lsp === true ? ["language-server diagnostics (the user's configuration names one server, `fixture`, for `*.txt` files)"] : []),
    ...(features.codeMode === true ? ["code mode (`run_code`; its programs call the scenario's tools)"] : []),
  ]
  return `*Engine:* offers ${offered.join("; ")}.`
}

function describeMessage(message: MessageView): string {
  const what = message.kind === "assistant" ? `${message.status}${message.error === null ? "" : ` ${message.error}`}` : message.kind
  const calls = message.calls.length === 0 ? "" : ` [${message.calls.map((call) => call.split(" ").slice(1).join(" ")).join(", ")}]`
  const command = message.command === null ? "" : ` (${message.command})`
  return `${message.id} ${what}${command}${calls}${message.excluded === null ? "" : ` excluded:${message.excluded}`}`
}

function describeClaim(state: Projection): string {
  const execution = state.session.execution
  if (execution === null) return "released"
  const crashes = execution.crashResumes === 0 ? "" : `, ${execution.crashResumes} crash resume(s)`
  const interrupting = execution.interrupting === null ? "" : `, ${execution.interrupting} interrupt requested`
  return `${execution.status}${crashes}${interrupting}`
}

function sentence(text: string): string {
  const upper = text.charAt(0).toUpperCase() + text.slice(1)
  return /[.!?]$/.test(upper) ? upper : `${upper}.`
}
