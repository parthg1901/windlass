/**
 * macOS backend: `sandbox-exec` with a generated Seatbelt (SBPL) profile.
 *
 * UNTESTED ON A REAL MAC. This was written and unit-tested on Linux; the
 * profile text is checked, but no command has been run under it. Expect to
 * add allowances (mach services, sysctls, ioctls) the first time it runs on
 * macOS. It fails closed: a missing allowance breaks a command, it does not
 * open a hole.
 *
 * The profile denies by default and allows what ordinary command-line tools
 * need. Paths come in as `-D` parameters rather than being spliced into the
 * profile, so no path needs escaping. Later rules win over earlier ones, so
 * the hidden-path denials come last. sandbox-exec applies the profile and
 * execs the command in place: the process tree, process group and signals are
 * the same as without the sandbox.
 */
import { realpathSync } from "node:fs"
import type { SandboxPolicy } from "./policy.ts"

export const SANDBOX_EXEC_PATH = "/usr/bin/sandbox-exec"

export interface SeatbeltProfile {
  readonly profile: string
  /** `-D` parameters the profile reads with `(param "NAME")`. */
  readonly params: ReadonlyArray<readonly [string, string]>
}

/** Read-only system locations when `readRest` is false. */
const SYSTEM_READ = ["/usr", "/bin", "/sbin", "/System", "/Library", "/private/etc", "/private/var/db/timezone", "/opt/homebrew", "/usr/local", "/Applications/Xcode.app", "/Library/Developer/CommandLineTools", "/dev"]

const BASE = `(version 1)
(deny default)

; processes: may start programs and signal or inspect only processes in this sandbox
(allow process-exec)
(allow process-fork)
(allow signal (target same-sandbox))
(allow process-info* (target same-sandbox))

; system information and shared libraries' needs
(allow sysctl-read)
(allow user-preference-read)
(allow ipc-posix-sem)
(allow ipc-posix-shm-read* ipc-posix-shm-write-create ipc-posix-shm-write-data)
(allow iokit-open (iokit-registry-entry-class "RootDomainUserClient"))
(allow mach-lookup
  (global-name "com.apple.system.opendirectoryd.libinfo")
  (global-name "com.apple.system.notification_center")
  (global-name "com.apple.system.logger")
  (global-name "com.apple.logd")
  (global-name "com.apple.diagnosticd")
  (global-name "com.apple.cfprefsd.daemon")
  (global-name "com.apple.cfprefsd.agent")
  (global-name "com.apple.PowerManagement.control"))

; terminals and the standard devices
(allow pseudo-tty)
(allow file-read* file-write* file-ioctl
  (literal "/dev/null")
  (literal "/dev/zero")
  (literal "/dev/tty")
  (literal "/dev/ptmx")
  (regex #"^/dev/ttys[0-9]+$")
  (regex #"^/dev/fd/[0-9]+$"))
(allow file-read* (literal "/dev/random") (literal "/dev/urandom") (literal "/dev/dtracehelper"))
; path resolution needs metadata everywhere (not contents)
(allow file-read-metadata)
`

const NETWORK_ON = `
; network: on (unrestricted), with the services DNS and TLS verification use
(allow network*)
(allow system-socket)
(allow mach-lookup
  (global-name "com.apple.SystemConfiguration.configd")
  (global-name "com.apple.SystemConfiguration.DNSConfiguration")
  (global-name "com.apple.dnssd.service")
  (global-name "com.apple.networkd")
  (global-name "com.apple.nehelper")
  (global-name "com.apple.trustd")
  (global-name "com.apple.trustd.agent")
  (global-name "com.apple.ocspd"))
`

/** The profile and its parameters for `policy`. Paths are canonicalised (macOS: /tmp is /private/tmp) when they exist. */
export function seatbeltProfile(policy: SandboxPolicy): SeatbeltProfile {
  const params: Array<[string, string]> = []
  const param = (prefix: string, path: string) => {
    const name = `${prefix}_${params.filter(([key]) => key.startsWith(`${prefix}_`)).length}`
    params.push([name, canonical(path)])
    return `(subpath (param "${name}"))`
  }

  const reads = policy.readRest
    ? "(allow file-read*)"
    : `(allow file-read*\n  (literal "/")\n  ${[...SYSTEM_READ, ...(policy.readableRoots ?? [])].map((path) => param("READABLE", path)).join("\n  ")})`
  const writableRoots = [...policy.writableRoots, ...(policy.tempRoot ? [policy.tempRoot] : [])]
  const writes = writableRoots.length > 0 ? `(allow file-read* file-write*\n  ${writableRoots.map((path) => param("WRITABLE", path)).join("\n  ")})` : "; no writable roots"
  const hidden =
    policy.hiddenPaths.length > 0
      ? `(deny file-read* file-write*\n  ${policy.hiddenPaths.map((path) => param("HIDDEN", path)).join("\n  ")})`
      : "; no hidden paths"
  const network = policy.network.mode === "on" ? NETWORK_ON : "\n; network: off (no network-* rules: TCP, UDP and unix-socket connections are denied)\n"

  const profile = [
    "; Generated by the sandbox module. UNTESTED ON A REAL MAC; see seatbelt.ts.",
    BASE,
    "; reads",
    reads,
    "",
    "; writes",
    writes,
    network,
    "; hidden paths: last, so they win over every allow above",
    hidden,
    "",
  ].join("\n")
  return { profile, params }
}

export function seatbeltArgv(policy: SandboxPolicy, command: readonly string[], sandboxExecPath = SANDBOX_EXEC_PATH): string[] {
  const generated = seatbeltProfile(policy)
  return [sandboxExecPath, "-p", generated.profile, ...generated.params.map(([name, value]) => `-D${name}=${value}`), "--", ...command]
}

function canonical(path: string) {
  try {
    return realpathSync(path)
  } catch {
    return path.replace(/^\/(tmp|var|etc)(?=\/|$)/, "/private/$1")
  }
}
